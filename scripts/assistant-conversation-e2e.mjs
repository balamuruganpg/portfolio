import assert from "node:assert/strict";

const base = process.argv[2] || "http://localhost:3000";
const history = [];
const interval = Number(process.env.CASE_DELAY_MS ?? 12_000);
async function ask(question, conversation = history) {
  if (interval) await new Promise(resolve => setTimeout(resolve, interval));
  const response = await fetch(base + "/api/chat", { method: "POST", headers: { "Content-Type": "application/json", "x-forwarded-for": "rag-conversation-regression" }, body: JSON.stringify({ question, history: conversation }) });
  assert.equal(response.status, 200);
  const data = await response.json();
  assert.equal(data.mode, "llm", `${question}: expected model-generated source-checked answer, got ${data.mode}`);
  assert.equal(data.provider, "Groq");
  assert.ok(data.citations.length > 0);
  console.log(JSON.stringify({ question, answer: data.answer, retrieval: data.retrieval, sources: data.citations.map(c => c.label), actions: data.actions }));
  conversation.push({ role: "user", text: question }, { role: "assistant", text: data.answer, citations: data.citations });
  return data;
}
await ask("Tell me about the IIM Mumbai certificate");
const broad = await ask("Certificates?");
assert.match(broad.answer, /45/);
assert.ok(broad.citations.some(c => c.href === "#certs"));
assert.ok(broad.actions.some(a => a.type === "credentials" && a.query === ""));
const oracle = await ask("What about the Oracle ones?");
assert.match(oracle.answer, /(?:4|four)/i); assert.match(oracle.answer, /Data Science/);
assert.ok(oracle.actions.some(a => a.query === "Oracle"));
const progress = await ask("Which ones are in progress?");
assert.match(progress.answer, /Deep Learning Specialization/); assert.match(progress.answer, /in progress/i);
const proof = await ask("Give the Oracle Data Science credential ID and proof");
assert.match(proof.answer, /102569553OCI25DSOCP/);
assert.ok(proof.citations.some(c => c.href === "/credentials/oci-data-science-2025.pdf"));
const semantic = await ask("What evidence suggests he can build reliable AI systems?", []);
assert.equal(semantic.retrieval.strategy, "semantic");
assert.ok(semantic.citations.some(c => /VeraScan|Bull\/Bear|CertiRoute|Agent/i.test(c.label)));
const comparison = await ask("Compare VeraScan and Bull/Bear Autopilot for engineering evidence", []);
assert.match(comparison.answer, /VeraScan/); assert.match(comparison.answer, /Bull\/Bear/);
assert.ok(comparison.citations.some(c => /VeraScan/.test(c.label)));
assert.ok(comparison.citations.some(c => /Bull\/Bear/.test(c.label)));
console.log("PASS 7 conversational API turns generated by Groq, with broad/category/proof retrieval, semantic routing and comparisons");
